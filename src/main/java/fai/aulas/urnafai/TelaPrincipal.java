    private void registrarVoto(String cargo, String valor){
        String valorCifrado = cifrarCesar(valor, CHAVE_CIFRA);

        try (java.io.BufferedWriter bw = new java.io.BufferedWriter(new java.io.FileWriter(ARQUIVO_VOTOS, true))){
            bw.write(cargo + ";" + valorCifrado);
            bw.newLine();
        } catch(java.io.IOException e){
            e.printStackTrace();
        }
    }
    
    private String cifrarCesar(String texto, int chave){
        StringBuilder sb = new StringBuilder();

        for(char c : texto.toCharArray()){
            if(Character.isDigit(c)){
                int novoDigito = (Character.getNumericValue(c) + chave) % 10;
                sb.append(novoDigito);
            } else if(Character.isUpperCase(c)){
                char novaLetra = (char) ('A' + (c - 'A' + chave) % 26);
                sb.append(novaLetra);
            } else {
                sb.append(c);
            }
        }

        return sb.toString();
    }
    
    private String decifrarCesar(String texto, int chave){
        StringBuilder sb = new StringBuilder();
        for(char c : texto.toCharArray()){
            if(Character.isDigit(c)){
                int digito = Character.getNumericValue(c);
                int original = ((digito - chave) % 10 + 10) % 10;
                sb.append(original);
            } else if(Character.isUpperCase(c)){
                int letra = c - 'A';
                int original = ((letra - chave) % 26 + 26) % 26;
                sb.append((char) ('A' + original));
            } else {
                sb.append(c);
            }
        }
        return sb.toString();
    }
    
    private Map<String, Integer> contarVotos(String cargo){
        Map<String, Integer> contagem = new HashMap<>();
        File arquivo = new File(ARQUIVO_VOTOS);
        if(!arquivo.exists()){
            return contagem;
        }
        
        try (BufferedReader br = new BufferedReader(new FileReader(arquivo))){
            String linha;
            while ((linha = br.readLine()) != null){
                String[] partes = linha.split(";", -1);
                if(partes.length == 2 && partes[0].equals(cargo)){
                    String valor = decifrarCesar(partes[1], CHAVE_CIFRA);
                    contagem.merge(valor, 1, Integer::sum);
                }
            }
        } catch(IOException e){
            e.printStackTrace();
        }
        return contagem;
    }
    
    private void montarSecaoApuracao(String cargo, int indiceCargo, JPanel destino){
       JLabel lblTitulo = new JLabel(cargo);
       lblTitulo.setFont(new Font("Segoe UI", Font.BOLD, 16));
       lblTitulo.setAlignmentX(Component.LEFT_ALIGNMENT);
       lblTitulo.setBorder(BorderFactory.createEmptyBorder(0,0,10,0));
       destino.add(lblTitulo);
       
       Map<String, Integer> contagem = contarVotos(cargo);
       int total = 0;
       for(int v : contagem.values()){
           total += v;
       }
       
       List<Candidato> candidatos = new ArrayList<>();
       for (Candidato c : daoPorCargo[indiceCargo].listarTodos()) {
           if (cargo.equals(c.getCargo())) {
               candidatos.add(c);
           }
       }
            
       List<Object[]> linhas = new ArrayList<>();
       
       for(Candidato c : candidatos){
           int votos = contagem.getOrDefault(c.getNumero(), 0);
           linhas.add(new Object[]{c.getNome() + "(" + c.getNumero() + ")", votos});
       }
       
       int votosNulos = 0;
       for(Map.Entry<String, Integer> entry: contagem.entrySet()){
           String chave = entry.getKey();
           if(chave.equals("BRANCO")){
               continue;
           }
           boolean encontrado = false;
           for(Candidato c : candidatos){
               if(c.getNumero().equals(chave)){
                   encontrado = true;
                   break;
               }
           }
           if(!encontrado){
               votosNulos += entry.getValue();
           }
       }
       
       linhas.add(new Object[]{"Votos em Branco", contagem.getOrDefault("BRANCO", 0)});
       linhas.add(new Object[]{"Votos Nulos", votosNulos});
       
       linhas.sort((a,b) -> (Integer) b[1] - (Integer) a[1]);
       
       for(Object[] linha : linhas){
           String nome = (String) linha[0];
           int votos = (Integer) linha[1];
           double percentual = total == 0 ? 0 : (votos * 100.0 / total);
           destino.add(criarLinhaApuracao(nome, votos, percentual));
           destino.add(Box.createVerticalStrut(8));
       }
    }
    
    private JPanel criarLinhaApuracao(String nome, int votos, double percentual) {
        JPanel linha = new JPanel(new BorderLayout(10, 4));
        linha.setBackground(Color.WHITE);
        linha.setBorder(BorderFactory.createEmptyBorder(6, 10, 6, 10));
        linha.setMaximumSize(new Dimension(Integer.MAX_VALUE, 60));
        linha.setAlignmentX(Component.LEFT_ALIGNMENT);

        JLabel lblNome = new JLabel(nome);
        lblNome.setFont(new Font("Segoe UI", Font.BOLD, 13));

        JLabel lblVotos = new JLabel(
                votos + " votos (" + String.format("%.1f", percentual) + "%)");
        lblVotos.setFont(new Font("Segoe UI", Font.PLAIN, 12));
        lblVotos.setForeground(new Color(80, 80, 80));
        JPanel topo = new JPanel(new BorderLayout());
        topo.setOpaque(false);
        topo.add(lblNome, BorderLayout.WEST);
        topo.add(lblVotos, BorderLayout.EAST);

        JPanel barraFundo = new JPanel(null);
        barraFundo.setBackground(new Color(224, 224, 224));
        barraFundo.setPreferredSize(new Dimension(400, 14));

        JPanel barraPreenchida = new JPanel();
        barraPreenchida.setBackground(new Color(63, 127, 191));
        int largura = (int) (400 * (percentual / 100.0));
        barraPreenchida.setBounds(0, 0, largura, 14);
        barraFundo.add(barraPreenchida);

        linha.add(topo, BorderLayout.NORTH);
        linha.add(barraFundo, BorderLayout.CENTER);

        return linha;
    }
    
