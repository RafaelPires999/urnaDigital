    private void iniciarCargo(int indice){
        cargoAtual = indice;
        numeroDigitado.setLength(0);
        votoBranco = false;
        conferindoNome = false;
        
        lblVisorCargo.setText(Cargos[cargoAtual]);
        lblVisorNome.setText("");
        lblVisorPartido.setText("");
        lblVisorFoto.setIcon(null);
        lblVisorVice.setText("");
        lblVisorVice.setVisible(false);
        
        atualizarCaixinhas();
    }
    
    private void atualizarCaixinhas(){
        JLabel[] caixinhas = {lblDigito1, lblDigito2, lblDigito3, lblDigito4, lblDigito5};
        int quantidade = num_Digitos_Cargo[cargoAtual];
        
        for (int i = 0; i < caixinhas.length; i++){
            caixinhas[i].setVisible(i < quantidade);
            caixinhas[i].setText("");
        }
        
        for (int i = 0; i < numeroDigitado.length(); i++){
            caixinhas[i].setText(String.valueOf(numeroDigitado.charAt(i)));
        }
    }
    
